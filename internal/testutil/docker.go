//go:build integration

package testutil

import (
	"context"
	"fmt"
	"os"
	"os/exec"
	"strings"
	"testing"
	"time"

	"github.com/jmoiron/sqlx"
)

// Run starts a disposable PostgreSQL container per test package unless the
// caller supplies TEST_DATABASE_URL (for example, a database in Compose).
func Run(m *testing.M) int {
	if os.Getenv("TEST_DATABASE_URL") != "" {
		return m.Run()
	}
	name := fmt.Sprintf("dept-api-tests-%d-%d", os.Getpid(), time.Now().UnixNano())
	docker := func(args ...string) (string, error) {
		ctx, cancel := context.WithTimeout(context.Background(), 2*time.Minute)
		defer cancel()
		out, err := exec.CommandContext(ctx, "docker", args...).CombinedOutput()
		if err != nil {
			return "", fmt.Errorf("docker %s: %w: %s", args[0], err, out)
		}
		return strings.TrimSpace(string(out)), nil
	}
	// Name is generated by this process; cleanup never touches a user's database.
	defer func() {
		if _, err := docker("rm", "--force", name); err != nil {
			fmt.Fprintln(os.Stderr, "test container cleanup:", err)
		}
	}()
	if _, err := docker("run", "--detach", "--rm", "--name", name,
		"--publish", "127.0.0.1::5432", "--env", "POSTGRES_PASSWORD=test", "--env", "POSTGRES_DB=department_test", "postgres:15-alpine"); err != nil {
		fmt.Fprintln(os.Stderr, err)
		return 1
	}
	address, err := docker("port", name, "5432/tcp")
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		return 1
	}
	dsn := "postgres://postgres:test@" + address + "/department_test?sslmode=disable"
	db, err := sqlx.Open("postgres", dsn)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		return 1
	}
	defer db.Close()
	ctx, cancel := context.WithTimeout(context.Background(), time.Minute)
	defer cancel()
	for {
		pingCtx, pingCancel := context.WithTimeout(ctx, time.Second)
		err = db.PingContext(pingCtx)
		pingCancel()
		if err == nil {
			break
		}
		select {
		case <-ctx.Done():
			fmt.Fprintln(os.Stderr, "test PostgreSQL did not become ready:", err)
			return 1
		case <-time.After(250 * time.Millisecond):
		}
	}
	if err := os.Setenv("TEST_DATABASE_URL", dsn); err != nil {
		fmt.Fprintln(os.Stderr, err)
		return 1
	}
	return m.Run()
}
